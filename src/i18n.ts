export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { zh, en };

let currentLocale: Locale = 'zh';

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

export function isMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(zh, value);
}

export function t(key: MessageKey, params: MessageParams = {}): string {
  return MESSAGES[currentLocale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(params[name] ?? placeholder));
}

/** Picks the first supported language from the browser preferences. */
export function detectLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith('zh')) return 'zh';
    if (normalized.startsWith('en')) return 'en';
  }
  return 'en';
}
